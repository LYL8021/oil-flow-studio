// Run from the complete upstream repository before committing the deployment copy.
// The self-contained Cloudflare copy does not need this command when deploying.
import {readFile, writeFile, mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {dirname, resolve} from 'node:path';

const directory=dirname(fileURLToPath(import.meta.url));
const canonical=resolve(directory,'..');
let drawings,feedback,snapshots;
try {
  [drawings,feedback,snapshots]=await Promise.all([
    readFile(resolve(canonical,'drawings-worker.js'),'utf8'),
    readFile(resolve(canonical,'feedback-worker.js'),'utf8'),
    readFile(resolve(canonical,'d1-snapshots.js'),'utf8')
  ]);
} catch {
  throw new Error('請在完整 oil-flow-studio 程式庫執行 refresh-source；獨立部署副本直接使用已附的 worker.js。');
}

const importLines=["import {handleDrawings} from './drawings-worker.js';","import {createD1SnapshotStore} from './d1-snapshots.js';"];
for(const line of importLines){
  if(!feedback.split('\n').includes(line))throw new Error('後端匯入已變更，請先更新 Cloudflare 打包規則，勿發布不同步的 Worker。');
  feedback=feedback.replace(line+'\n','');
}
drawings=drawings.replace(/^export /gm,'');
snapshots=snapshots.replace(/^export /gm,'');
if (/^\s*import\b/m.test(drawings+'\n'+feedback+'\n'+snapshots)) throw new Error('後端新增模組，請先更新 Cloudflare 打包規則。');
const header='// Generated by refresh-source.mjs from ../d1-snapshots.js, ../drawings-worker.js and ../feedback-worker.js.\n// Edit canonical sources, refresh, test, then commit this self-contained deployment copy.\n';
const pendingMigrations=[];
for (const [source,target] of [['feedback-schema.sql','0001_feedback.sql'],['drawings-schema.sql','0002_drawings.sql'],['d1-snapshots-schema.sql','0003_d1_snapshots.sql']]) {
  const contents=await readFile(resolve(canonical,source));
  const file=resolve(directory,'migrations',target);
  let previous;
  try { previous=await readFile(file); } catch(error) { if(error.code!=='ENOENT')throw error; }
  if (previous&&!previous.equals(contents)) throw new Error('既有遷移 '+target+' 與來源不同；已發布遷移不可修改，請另加新的遷移。');
  if(!previous)pendingMigrations.push({file,contents});
}
await mkdir(resolve(directory,'migrations'),{recursive:true});
for(const {file,contents} of pendingMigrations)await writeFile(file,contents);
await writeFile(resolve(directory,'worker.js'),header+'const createD1SnapshotStore=(()=>{\n'+snapshots+'\nreturn createD1SnapshotStore;\n})();\nconst handleDrawings=(()=>{\n'+drawings+'\nreturn handleDrawings;\n})();\n'+feedback);
console.log('Cloudflare Worker refreshed; existing schema migrations verified.');
